public class clase_2_For {
    public static void main(String[] args) {
        // Blucle repetitivo for
        int[] lista = {1, 4, 3, 4, 6};
        System.out.println(lista[2]);
        // Creacion de un bucle for para imprimir toda la lista
        // for (inicializacion del contador ; condicion de parada ; pasos)
        for (int i = 0; i < lista.length; i++) {
            System.out.println(lista[i]);
        }
        // EJERCICIO: Numeros amigos
        // Se imprime en pantalla los clase_2.divisores del numero
        // Y si la suma de todos da el mismo numero
    }
}
